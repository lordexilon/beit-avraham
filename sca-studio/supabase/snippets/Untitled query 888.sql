-- ============================================================
-- CAPA RAG: KNOWLEDGE BASE (pgvector)
-- ============================================================
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;

CREATE TABLE IF NOT EXISTS fsca.knowledge_base (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name TEXT NOT NULL,
    source_file TEXT NOT NULL,
    content TEXT NOT NULL,
    embedding vector(768),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Agregar columnas si no existen
ALTER TABLE fsca.knowledge_base ADD COLUMN IF NOT EXISTS embedding vector(768);

-- Índice ivfflat (idempotente)
CREATE INDEX IF NOT EXISTS knowledge_base_embedding_idx ON fsca.knowledge_base
    USING ivfflat (embedding vector_cosine_ops) WITH (lists = 100);

-- Función RPC (CREATE OR REPLACE = siempre seguro)
CREATE OR REPLACE FUNCTION fsca.match_knowledge (
  query_embedding vector(768),
  match_threshold float,
  match_count int,
  p_project_name text
)
RETURNS TABLE (
  id bigint,
  source_file text,
  content text,
  similarity float
)
LANGUAGE sql STABLE
AS $$
  SELECT
    knowledge_base.id,
    knowledge_base.source_file,
    knowledge_base.content,
    1 - (knowledge_base.embedding <=> query_embedding) AS similarity
  FROM fsca.knowledge_base
  WHERE 1 - (knowledge_base.embedding <=> query_embedding) > match_threshold
    AND knowledge_base.project_name = p_project_name
  ORDER BY knowledge_base.embedding <=> query_embedding
  LIMIT match_count;
$$;

-- Permisos RAG
DROP POLICY IF EXISTS "Permitir todo a knowledge_base" ON fsca.knowledge_base;
CREATE POLICY "Permitir todo a knowledge_base" ON fsca.knowledge_base FOR ALL USING (true) WITH CHECK (true);
ALTER TABLE fsca.knowledge_base ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON fsca.knowledge_base TO anon, authenticated;
GRANT EXECUTE ON FUNCTION fsca.match_knowledge TO anon, authenticated;
