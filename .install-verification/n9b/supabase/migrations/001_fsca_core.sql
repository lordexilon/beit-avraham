    USING ivfflat (embedding vector_cosine_ops) WITH (lists = 100);

-- 8. RPC: match_knowledge (Búsqueda vectorial de similitud de coseno)
CREATE OR REPLACE FUNCTION fsca.match_knowledge (
  query_embedding vector(768),
  match_threshold float,
  match_count int,
  p_project_name text
)
RETURNS TABLE (
  id bigint,
  source_file text,
  content text,
  similarity float
)
LANGUAGE sql STABLE
AS $$
  SELECT
    knowledge_base.id,
    knowledge_base.source_file,
    knowledge_base.content,
    1 - (knowledge_base.embedding <=> query_embedding) AS similarity
  FROM fsca.knowledge_base
  WHERE 1 - (knowledge_base.embedding <=> query_embedding) > match_threshold
    AND knowledge_base.project_name = p_project_name
  ORDER BY knowledge_base.embedding <=> query_embedding
  LIMIT match_count;
$$;

